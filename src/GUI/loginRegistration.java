        try {
            String username = jTextField7.getText();
            String fname = jTextField2.getText();
            String lname = jTextField3.getText();
            String email = jTextField6.getText();
            String password = String.valueOf(jPasswordField1.getPassword());
            String nic = jTextField4.getText();
            String mobile = jTextField5.getText();
            String gender = String.valueOf(jComboBox1.getSelectedItem());
            String type = String.valueOf(jComboBox2.getSelectedItem());

            if (username.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Enter Your Username", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (!username.matches("^[a-z]+$")) {
                JOptionPane.showMessageDialog(this, "Invalid username. Only lowercase letters are allowed", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (fname.isBlank()) {
                JOptionPane.showMessageDialog(this, "Enter Your First Name", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (lname.isBlank()) {
                JOptionPane.showMessageDialog(this, "Enter Your Last Name", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (email.isBlank()) {
                JOptionPane.showMessageDialog(this, "Enter Your Email", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (!email.matches("^(?=.{1,64}@)[A-Za-z0-9\\+_-]+(\\.[A-za-z0-9\\+_-]+)*@[^-][A-za-z0-9\\+-]+(\\.[A-za-z0-9\\+-]+)*(\\.[A-Za-z]{2,})$")) {
                JOptionPane.showMessageDialog(this, "Invalid Email", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (password.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Enter Your Password", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (nic.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Enter Your NIC", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (!nic.matches("^(([5,6,7,8,9]{1})([0-9]{1})([0,1,2,3,5,6,7,8]{1})([0-9]{6})([v|V|x|X]))|"
                    + "(([1,2]{1})([0,9]{1})([0-9]{2})([0,1,2,3,5,6,7,8]{1})([0-9]{7}))")) {
                JOptionPane.showMessageDialog(this, "Invalid NIC", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (mobile.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Enter Your Mobile", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (!mobile.matches("^07[01245678]{1}[0-9]{7}$")) {
                JOptionPane.showMessageDialog(this, "Invalid Mobile Number", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (gender.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please Select a Gender", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (type.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please Select a Type", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {

                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `users` WHERE `username`='" + username + "' OR `email`='" + email + "'");

                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "User already Registered", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {

                    Date date = new Date();
                    SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

                    MySQL.executeIUD("INSERT INTO `users`(`username`,`first_name`,`last_name`,`password_hash`,`email`,`nic`,`mobile`,`user_type_id`,`gender_id`)"
                            + "VALUES ('" + username + "','" + fname + "','" + lname + "','" + password + "','" + email + "','" + nic + "','" + mobile + "','" + userTypeMap.get(type) + "','" + userGenderMap.get(gender) + "')");

                    JOptionPane.showMessageDialog(this, "User registered Successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                    reset();
                    this.dispose();
                    loginRegistration loginRegister = new loginRegistration();
                    loginRegister.setVisible(true);

                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
